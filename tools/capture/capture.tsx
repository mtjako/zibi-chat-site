import React from 'react';
import {createRoot} from 'react-dom/client';
import {createMemoryRouter,RouterProvider} from 'react-router';
import RootLayout from '@/routes/root-layout';
import Session from '@/harness/claude/components/current-session';
import {HarnessProvider} from '@/components/harness-provider';
import {ThemeProvider} from '@/components/theme-provider';
import i18n from '@/i18n';
import '@/style.css';
const params=new URLSearchParams(location.search);
await i18n.changeLanguage(params.get('lang')||'pl');
const router=createMemoryRouter([{element:<RootLayout/>,children:[{path:'/current-session',element:<Session/>}]}],{initialEntries:['/current-session']});
createRoot(document.getElementById('root')!).render(<ThemeProvider defaultTheme={(params.get('theme')||'light') as 'light'|'dark'} storageKey="capture-theme"><HarnessProvider><RouterProvider router={router}/></HarnessProvider></ThemeProvider>);
