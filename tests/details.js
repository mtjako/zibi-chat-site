async (page) => {
 const check=(value,message)=>{if(!value)throw new Error(message);};
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/*',route=>route.continue());
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('http://127.0.0.1:3001/pl/');
 await page.locator('img[data-shot]').first().evaluate(img=>img.decode());
 check(await page.locator('.shot-transition').count()===0,'No initial-load overlay');
 const theme=await page.locator('html').getAttribute('data-theme');
 const target=theme==='dark'?'light':'dark';
 await page.evaluate(target=>window.sitePreferences.setTheme(target),target);
 await page.waitForFunction(()=>{const overlay=document.querySelector('.shot-transition');if(!overlay)return false;overlay.getAnimations().forEach(a=>a.pause());return true;});
 const fade=await page.locator('.shot-transition').first().evaluate(el=>({hidden:el.getAttribute('aria-hidden'),alt:el.alt,old:el.src,parent:el.parentElement.querySelector('img[data-shot]').src,animation:el.getAnimations().length}));
 check(fade.hidden==='true'&&fade.alt===''&&fade.animation===1,'Decorative crossfade');
 check(fade.old.includes('-'+theme+'-')&&fade.parent.includes('-'+target+'-'),'Old and new screenshots crossfade');
 await page.locator('.shot-transition').evaluateAll(els=>els.forEach(el=>el.getAnimations().forEach(a=>a.finish())));
 await page.waitForFunction(()=>document.querySelectorAll('.shot-transition').length===0);
 await page.evaluate(()=>{window.sitePreferences.setTheme('light');window.sitePreferences.setTheme('dark');window.sitePreferences.setTheme('light');});
 await page.waitForFunction(()=>document.documentElement.dataset.theme==='light'&&document.querySelector('img[data-shot]').src.includes('-light-'));
 await page.waitForFunction(()=>document.querySelectorAll('.shot-transition').length===0);

 await page.locator('.bento-sessions').evaluate(el=>el.scrollIntoView({behavior:'instant',block:'center'}));
 await page.waitForFunction(()=>document.querySelector('.bento-sessions').dataset.motionState==='entered');
 const row=page.locator('.app-thread').first();
 const session=await row.evaluate(el=>({time:el.querySelector('.app-thread-time').textContent,status:el.querySelector('.app-thread-dot').dataset.status,animations:el.getAnimations({subtree:true}).map(a=>a.animationName)}));
 check(session.time==='2m' && session.status==='working','Real row keeps last activity time and working status');
 check(session.animations.length===0,'App status dots remain still');
 check(await page.locator('.session-done,.session-status,.session-demo').count()===0,'No invented completion UI');
 await page.locator('.bento-sessions').evaluate(el=>el.getAnimations().forEach(a=>a.finish()));
 await page.locator('.bento-sessions').hover();
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('.bento-sessions')).transform.includes('-3'));
 check(await page.locator('.bento-sessions').evaluate(el=>getComputedStyle(el,'::after').opacity)==='1','Hover border highlight');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('.bento-sessions')).transform==='none');
 check(await row.evaluate(el=>el.getAnimations({subtree:true}).length)===0,'Session remains static with reduced motion');
 await page.evaluate(()=>window.sitePreferences.setTheme('dark'));
 check(await page.locator('.shot-transition').count()===0,'No crossfade in reduced motion');
 check((await page.locator('img[data-shot]').first().getAttribute('src')).includes('-dark-'),'Reduced-motion screenshot updates immediately');
 await page.goto('http://127.0.0.1:3001/en/');
 check(await page.locator('.app-thread-time').first().textContent()==='2m','English row preserves last activity time');
 const touch=await page.context().browser().newContext({hasTouch:true,isMobile:true,viewport:{width:390,height:844}});
 const mobile=await touch.newPage();await mobile.goto('http://127.0.0.1:3001/pl/');
 check(await mobile.evaluate(()=>!matchMedia('(hover:hover) and (pointer:fine)').matches),'Touch does not get hover');
 check(await mobile.locator('.bento-card').first().evaluate(el=>getComputedStyle(el).transform)==='none','No hover lift on touch');
 await touch.close();
 check(!errors.length,'Browser errors: '+errors.join('\n'));
 return {checks:'passed',fade,session,errors};
}
